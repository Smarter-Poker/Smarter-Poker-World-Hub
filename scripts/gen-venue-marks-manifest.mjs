#!/usr/bin/env node
/**
 * THE MARKS WE ACTUALLY HAVE.
 *
 * `public/images/venues/` holds a hand-cut 54px mark for some venues, not all.
 * The card used to request `/images/venues/<id>.png` for every venue and clear
 * it in onError, so a venue without a mark cost a 404 on every render. The
 * directory carries 478 venues and this folder carries 134 files, only 73 of
 * which match a venue still in the directory, so roughly 85% of the cards on a
 * city page were asking for a file that has never existed.
 *
 * The set is static: these are checked-in files, not data. So it is painted at
 * build time into a module the card can ask before it renders an <img>, which
 * is the same rule the console follows everywhere else. Paint what never
 * changes, print what does.
 *
 * Regenerate with `npm run gen:venue-marks`. A guard keeps the two in step.
 */
import fs from 'node:fs';
import path from 'node:path';

const MARKS_DIR = path.join(process.cwd(), 'public', 'images', 'venues');
const OUT = path.join(process.cwd(), 'src', 'components', 'poker-near-me', 'venueMarks.js');

export function readMarkIds(dir = MARKS_DIR) {
    if (!fs.existsSync(dir)) return [];
    return fs
        .readdirSync(dir)
        .filter((f) => /^\d+\.png$/.test(f))
        .map((f) => f.replace(/\.png$/, ''))
        .sort((a, b) => Number(a) - Number(b));
}

export function renderModule(ids) {
    return `// GENERATED BY scripts/gen-venue-marks-manifest.mjs. DO NOT EDIT BY HAND.
//
// The venue ids that have a checked-in 54px mark in public/images/venues/.
// The card asks this before it renders an <img>, so a venue without a mark
// costs no request at all rather than a 404 that onError then hides.
//
// Add or remove a file in that folder and run \`npm run gen:venue-marks\`.

const VENUE_MARK_IDS = new Set([
${ids.map((id) => `    '${id}',`).join('\n')}
]);

export function hasVenueMark(id) {
    if (id === null || id === undefined) return false;
    return VENUE_MARK_IDS.has(String(id));
}

export function venueMarkUrl(id) {
    return hasVenueMark(id) ? \`/images/venues/\${id}.png\` : '';
}

export { VENUE_MARK_IDS };
`;
}

const invokedDirectly = process.argv[1] && import.meta.url === `file://${path.resolve(process.argv[1])}`;
if (invokedDirectly) {
    const ids = readMarkIds();
    const next = renderModule(ids);
    const check = process.argv.includes('--check');
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (check) {
        if (current !== next) {
            console.error('venue marks manifest is stale. Run: npm run gen:venue-marks');
            process.exit(1);
        }
        console.log(`venue marks manifest OK (${ids.length} marks).`);
    } else {
        fs.writeFileSync(OUT, next);
        console.log(`wrote ${OUT} (${ids.length} marks).`);
    }
}
