function formatDiamonds(n) {
    return Number(n).toLocaleString('en-US');
}

/**
 * The headline number for a reward row.
 *   fixed payout  → '+15 Diamonds'
 *   streak-scaled → '5-25 Diamonds'   (daily_login: 5 on day 1 → 25 at day 11+)
 *   variable      → 'Up To 500 Diamonds' (easter eggs, priced by rarity)
 */
function formatAmount(r) {
    const max = r.maxDiamonds;
    if (!r.diamonds && max) return `Up To ${formatDiamonds(max)} Diamonds`;
    if (max && max > r.diamonds) return `${formatDiamonds(r.diamonds)}-${formatDiamonds(max)} Diamonds`;
    return `+${formatDiamonds(r.diamonds)} ${r.diamonds === 1 ? 'Diamond' : 'Diamonds'}`;
}

/** The real, honest frequency limit for a reward: never "unlimited". */
function formatLimit(r) {
    if (r.lifetime) return 'Once, Ever';
    if (r.oncePerYear) return 'Once Per Calendar Year';
    if (r.oncePerMonth) return 'Once Per Month';
    if (r.monthlyMax) return `Up To ${r.monthlyMax} Per Month`;
    if (r.oncePerTarget && r.maxPerDay > 1) return `Up To ${r.maxPerDay}/Day, One Payout Per Item Ever`;
    if (r.oncePerTarget) return '1/Day, One Payout Per Item Ever';
    if (r.maxPerDay > 1) return `Up To ${r.maxPerDay}/Day`;
    return '1/Day';
}

/** Which budget the payout is drawn from. Every line here has a ceiling. */
function formatCapNote(r) {
    if (r.category === 'secret') {
        return `Separate ${formatDiamonds(CATALOG_EASTER_EGG_MONTHLY_CAP)} ◆/Month Egg Budget`;
    }
    if (r.category === 'referral') return 'Separate Referral Budget, Own Monthly Limit';
    if (r.countsTowardDailyCap) {
        return `Counts Toward Your ${formatDiamonds(CATALOG_DAILY_CAP.free)} ◆/Day Cap`;
    }
    if (r.lifetime) return 'One-Time Onboarding Budget, Not Repeatable';
    return 'Separate Budget With Its Own Limit';
}

/**
 * The referral line is the one users misread most, so it spells out the full
 * release condition instead of a slogan. Numbers come from the catalog.
 */
function referralNote() {
    return [
        `${formatDiamonds(CATALOG_REFERRAL.referrer)} ◆ To You + ${formatDiamonds(CATALOG_REFERRAL.referee)} ◆ To Your Friend`,
        'Released Only After They Verify Email AND Phone AND Log In On 5 Separate Days',
        `Max ${CATALOG_REFERRAL.maxQualifiedPerMonth} Qualified Referrals Per Month`,
    ].join(' · ');
}

function buildNote(r) {
    if (r.key === 'referral_qualified') return referralNote();
    const gate = r.gate === 'vip' ? 'VIP Only' : 'Free';
    const bits = [formatLimit(r), formatCapNote(r), gate];
    if (r.serverOnly) bits.push('Awarded Automatically');
    return bits.join(' · ');
}

