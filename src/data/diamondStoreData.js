function projectReward(r) {
    return {
        id: r.key,
        icon: resolveIcon(r.icon),
        name: r.label,
        amount: formatAmount(r),
        note: buildNote(r),
        category: CATEGORIES[r.category] || r.category,
        // Extras for richer UIs. Safe to ignore: old consumers never read them.
        description: r.description,
        diamonds: r.diamonds,
        maxDiamonds: r.maxDiamonds || r.diamonds,
        maxPerDay: r.maxPerDay,
        gate: r.gate,
        lifetime: !!r.lifetime,
        countsTowardDailyCap: !!r.countsTowardDailyCap,
        serverOnly: !!r.serverOnly,
    };
}

