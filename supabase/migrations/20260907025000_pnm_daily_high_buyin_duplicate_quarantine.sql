      v_count, v_checksum;
  end if;

  select count(*), md5(string_agg(actual.id::text, ',' order by actual.id::text))
    into v_count, v_checksum
    from public.venue_daily_tournaments actual
    join pnm_duplicate_loser_ids expected using (id)
   where actual.is_active is true
     and actual.is_suppressed is not true
     and actual.data_quality in (
       'scraped_verified', 'scraped_inferred', 'manual_research'
