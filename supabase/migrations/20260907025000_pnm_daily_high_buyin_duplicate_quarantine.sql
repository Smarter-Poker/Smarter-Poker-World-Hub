    raise exception 'pre-flight failed: duplicate-loser ID set drifted (%, %)',
      v_count, v_checksum;
  end if;

  select count(*)
    into v_count
    from pnm_high_buyin_ids h
    join pnm_duplicate_loser_ids d using (id);
  if v_count <> 2 then
    raise exception 'pre-flight failed: expected two-row cohort overlap, found %', v_count;
  end if;

  select count(*), md5(string_agg(actual.id::text, ',' order by actual.id::text))
    into v_count, v_checksum
    from public.venue_daily_tournaments actual
    join pnm_high_buyin_ids expected using (id)
   where actual.is_active is true
     and actual.is_suppressed is not true
     and actual.data_quality = 'scraped_inferred'
     and actual.human_verified is false
     and actual.buy_in > 5000;
  if v_count <> 244
